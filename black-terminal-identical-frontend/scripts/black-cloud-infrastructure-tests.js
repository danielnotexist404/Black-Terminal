assert.doesNotMatch(compose, /image:\s*\S+:latest\b/i, "mutable latest image tags are forbidden");
assert.match(compose, /profiles:\s*\["live-execution"\]/, "real-funds workers must be isolated behind a Compose profile");
assert.match(compose, /BLACK_CLOUD_DEPLOYMENT_COMMIT:\s*\$\{BLACK_CLOUD_DEPLOYMENT_COMMIT\}/, "the central API must report its immutable release identity");
assert.match(releaseCompose, /frontend:[\s\S]*?image: \$\{BLACK_CLOUD_FRONTEND_IMAGE:\?/, "frontend release image must be supplied explicitly");
assert.match(releaseCompose, /api:[\s\S]*?image: \$\{BLACK_CLOUD_API_IMAGE:\?/, "API release image must be supplied explicitly");
for (const service of ["strategy-automation-worker", "black-cloud-demo-execution-worker", "black-cloud-execution-worker"]) {
  assert.match(releaseCompose, new RegExp(`\\n  ${service}:[\\s\\S]*?image: \\$\\{BLACK_CLOUD_RUNTIME_IMAGE:\\?`), `${service} must consume the explicitly selected immutable runtime image`);
}
assert.doesNotMatch(releaseCompose, /image: black-terminal-(?:frontend|api|runtime):/, "the release overlay must not silently derive mutable local tags");
assert.equal((releaseCompose.match(/^\s+BLACK_CLOUD_DEPLOYMENT_COMMIT:/gm) || []).length, 4, "API and all execution runtimes must report the release identity");
assert.equal((releaseCompose.match(/^\s+BLACK_CLOUD_IMAGE_REFERENCE:/gm) || []).length, 3, "all execution runtimes must report the immutable runtime image reference");
assert.equal((releaseCompose.match(/^\s+BLACK_CLOUD_IMAGE_DIGEST:/gm) || []).length, 3, "all execution runtimes must report Docker's verified runtime image digest");
assert.equal((releaseCompose.match(/BLACK_CLOUD_IMAGE_REFERENCE: \$\{BLACK_CLOUD_RUNTIME_IMAGE\}/g) || []).length, 3, "runtime telemetry must report the exact Compose image selection");
assert.match(runtimeExample, /BLACK_CLOUD_MAINNET_ENABLED=false/);
assert.match(runtimeExample, /EVENT_ALPHA_LIVE_EXECUTION_ENABLED=false/);
assert.match(runtimeExample, /IMM_ENABLED=false/);
assert.match(runtimeExample, /IMM_REQUIRED=false/);
assert.doesNotMatch(staging, /jdwlspxzoudgzxcghbjo|supabase\.co/i, "staging proxy must not retain a hosted Supabase fallback");
assert.doesNotMatch(production, /jdwlspxzoudgzxcghbjo|supabase\.co/i, "production proxy must not retain a hosted Supabase fallback");
assert.match(staging, /reverse_proxy supabase-kong:8000/);
assert.match(production, /reverse_proxy supabase-kong:8000/);
assert.match(prepare, /549db119c44c25167461812041ba198bde2b31a4/);
assert.match(initialize, /GOOGLE_OAUTH_CLIENT_ID/);
assert.match(initialize, /GOOGLE_ENABLED "true"/);
assert.match(fs.readFileSync("infra/black-cloud/supabase.override.yml", "utf8"), /GOTRUE_EXTERNAL_GOOGLE_REDIRECT_URI/);
assert.match(supabaseOverride, /BLACK_CLOUD_SUPABASE_STATE_ROOT[^\n]*\/postgres:\/var\/lib\/postgresql\/data/);
assert.match(supabaseOverride, /BLACK_CLOUD_SUPABASE_STATE_ROOT[^\n]*\/storage:\/var\/lib\/storage/);
assert.match(supabaseOverride, /supavisor:[\s\S]*ports: !override[\s\S]*127\.0\.0\.1:15432:5432[\s\S]*127\.0\.0\.1:16543:6543/, "Supavisor must replace upstream public bindings with loopback-only ports");
assert.match(fs.readFileSync("infra/black-cloud/docker-compose.backup.yml", "utf8"), /BLACK_CLOUD_SUPABASE_STATE_ROOT[^\n]*\/storage:\/source\/storage:ro/);
assert.match(stagingCompose, /127\.0\.0\.1:18080/);
assert.match(productionCompose, /80:80/);
assert.match(productionCompose, /443:443/);
assert.doesNotMatch(compose, /5432:5432|6379:6379|9000:9000/, "database, cache, and storage ports must not be public");
assert.match(databaseRestoreDrill, /--network none/);
assert.match(databaseRestoreDrill, /pg_restore[\s\S]*--exit-on-error/);
assert.match(databaseRestoreDrill, /supabase\/postgres:17\.6\.1\.136/);
assert.doesNotMatch(databaseRestoreDrill, /--network host|--privileged/);
assert.match(backupDockerfile, /COPY infra\/black-cloud\/scripts\/verify-backup\.sh \/usr\/local\/bin\/verify-backup/);
assert.match(backupOnce, /tar --xattrs --xattrs-include='\*'/, "Storage backup must preserve file-backend extended attributes");
assert.match(backupOnce, /black-cloud-backup-v2/);
assert.match(backupOnce, /mkdir "\$lock_dir"/, "backup staging must have an atomic single-writer lock");
assert.match(backupOnce, /black_cloud_backup_already_running/);
assert.match(backupVerify, /storageExtendedAttributes/);
